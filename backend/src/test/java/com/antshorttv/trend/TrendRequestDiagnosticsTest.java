package com.antshorttv.trend;

import static org.assertj.core.api.Assertions.*;
import com.antshorttv.trend.TrendModels.HttpPage;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

class TrendRequestDiagnosticsTest {
    @Test void retainsOnlyBoundedDiagnosticHeadersAndStripsRedirectSecrets() {
        var page = new HttpPage(403, "text/html", "Forbidden", Map.of(
            "Server", "openresty", "Set-Cookie", "session=secret",
            "Authorization", "Bearer secret", "X-Private", "secret",
            "Location", "https://example.com/login?token=secret#secret",
            "X-Amz-Cf-Id", "x".repeat(2000)), 12L);
        assertThat(page.headers()).containsEntry("server", "openresty");
        assertThat(page.headers()).containsEntry("location", "https://example.com/login");
        assertThat(page.headers()).doesNotContainKeys("set-cookie", "authorization", "x-private");
        assertThat(page.headers().get("x-amz-cf-id")).hasSize(512);
    }

    @Test void distinguishesExplicitGeoBlockFromGenericCloudfrontAndUnknown403() {
        var geo = inspect("The Amazon CloudFront distribution is configured to block access from your country. Request ID: abc-_123==");
        assertThat(geo.cause()).isEqualTo("GEO_RESTRICTED");
        assertThat(geo.provider()).isEqualTo("CLOUDFRONT");
        assertThat(geo.requestId()).isEqualTo("abc-_123==");
        var blocked = inspect("Request blocked. Generated by cloudfront (CloudFront)");
        assertThat(blocked.cause()).isEqualTo("EDGE_REQUEST_BLOCKED");
        assertThat(inspect("<h1>403 Forbidden</h1><center>openresty</center>").cause()).isEqualTo("HTTP_FORBIDDEN_UNCLASSIFIED");
        assertThat(inspect("Forbidden").provider()).isEqualTo("UNKNOWN");
    }

    @Test void successAndRedirectDoNotInventBlockingReasons() {
        var success=TrendRequestDiagnostics.inspect(0,"https://example.com/robots.txt",new HttpPage(200,"text/plain","User-agent: *"),Instant.EPOCH);
        assertThat(success.cause()).isEqualTo("NONE");
        assertThat(success.elapsedMillis()).isNull();
        var redirect=TrendRequestDiagnostics.inspect(0,"https://example.com/robots.txt",new HttpPage(302,"text/html",""),Instant.EPOCH);
        assertThat(redirect.cause()).isEqualTo("REDIRECT_NOT_FOLLOWED");
        assertThat(redirect.stage()).isEqualTo("ROBOTS_FETCH");
    }

    private TrendModels.RequestDiagnostic inspect(String body) {
        return TrendRequestDiagnostics.inspect(0,"https://example.com/robots.txt",new HttpPage(403,"text/html",body),Instant.EPOCH);
    }
}
