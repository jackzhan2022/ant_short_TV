package com.antshorttv.trend;

import static com.antshorttv.trend.TrendModels.*;
import java.net.URI;
import java.time.Instant;
import java.util.*;
import java.util.regex.Pattern;
import org.jsoup.Jsoup;

/** Evidence-based diagnostics only: never infer a WAF rule, geography or IP from a generic 403. */
final class TrendRequestDiagnostics {
    private static final Set<String> HEADER_NAMES = Set.of("server", "date", "content-type", "retry-after",
        "x-amz-cf-id", "x-amz-cf-pop", "x-cache", "cf-ray", "x-request-id", "location");
    private static final Pattern REQUEST_ID = Pattern.compile("Request ID:\\s*([A-Za-z0-9_+/=-]{1,512})(?:\\s|$)", Pattern.CASE_INSENSITIVE);
    private TrendRequestDiagnostics() {}

    static Map<String,String> safeHeaders(Map<String,String> input) {
        var output = new TreeMap<String,String>();
        if (input == null) return Map.of();
        input.forEach((key,value) -> {
            String name=key.toLowerCase(Locale.ROOT);
            if (!HEADER_NAMES.contains(name) || value==null) return;
            String safe=value;
            if (name.equals("location")) {
                try {
                    var uri=URI.create(value);
                    if (uri.isOpaque()) return;
                    safe=new URI(uri.getScheme(),null,uri.getHost(),uri.getPort(),uri.getPath(),null,null).toString();
                } catch (Exception ex) { return; }
            }
            safe=safe.replaceAll("[\\p{Cntrl}]", " ");
            output.put(name,safe.substring(0,Math.min(safe.length(),512)));
        });
        return Collections.unmodifiableMap(output);
    }

    static RequestDiagnostic inspect(int page, String url, HttpPage response, Instant at) {
        var headers=response.headers();
        String body=response.body()==null?"":response.body();
        String text=Jsoup.parse(body.substring(0,Math.min(body.length(),16384))).text();
        String lower=text.toLowerCase(Locale.ROOT);
        String server=headers.getOrDefault("server", "").toLowerCase(Locale.ROOT);
        boolean cloudfront=server.contains("cloudfront") || headers.containsKey("x-amz-cf-id")
            || lower.contains("generated by cloudfront") || lower.contains("amazon cloudfront distribution");
        String provider=cloudfront?"CLOUDFRONT":server.contains("openresty")||lower.contains("openresty")?"OPENRESTY":"UNKNOWN";
        String cause="NONE";
        if(response.status()==403) {
            cause=cloudfront && lower.contains("configured to block access from your country")?"GEO_RESTRICTED":
                cloudfront && lower.contains("request blocked")?"EDGE_REQUEST_BLOCKED":"HTTP_FORBIDDEN_UNCLASSIFIED";
        } else if(response.status()>=300 && response.status()<400) cause="REDIRECT_NOT_FOLLOWED";
        else if(response.status()!=200) cause="HTTP_ERROR";
        else if(page==0 && !response.contentType().toLowerCase(Locale.ROOT).startsWith("text/plain")) cause="ROBOTS_INVALID_CONTENT_TYPE";
        String requestId=headers.get("x-amz-cf-id");
        if(requestId==null) requestId=headers.get("x-request-id");
        if(requestId==null) requestId=headers.get("cf-ray");
        if(requestId==null && cloudfront) {
            var match=REQUEST_ID.matcher(text);
            if(match.find()) requestId=match.group(1);
        }
        return new RequestDiagnostic(page,page==0?"ROBOTS_FETCH":"PAGE_FETCH",url,response.status(),
            response.contentType(),at,response.elapsedMillis(),headers,provider,cause,requestId);
    }
}
